"""Utilidades comunes de las pruebas: una caché del sistema con entradas de ejemplo."""

from __future__ import annotations

from collections.abc import AsyncIterator
from pathlib import Path

import pytest

from nyx.index.aliases import generate
from nyx.index.db import IndexDB
from nyx.index.model import Entry, Kind, Launch, LaunchKind
from nyx.index.scanners.tables import scan_settings, scan_websites
from nyx.index.service import SystemIndex
from nyx.settings.model import Settings
from nyx.tools.base import ToolContext


def app(name: str, app_id: str, process: str | None = None) -> Entry:
    return Entry(
        key=f"app:{app_id.casefold()}",
        kind=Kind.APP,
        name=name,
        launch=Launch(LaunchKind.APPS_FOLDER, app_id),
        source="test",
        process=process,
        aliases=generate(name),
    )


def game(name: str, uri: str, process: str | None = None) -> Entry:
    return Entry(
        key=f"game:{uri}",
        kind=Kind.GAME,
        name=name,
        launch=Launch(LaunchKind.URI, uri),
        source="test",
        process=process,
        aliases=generate(name),
    )


def folder(name: str, path: str, extra: tuple[str, ...] = ()) -> Entry:
    return Entry(
        key=f"folder:{path.casefold()}",
        kind=Kind.FOLDER,
        name=name,
        launch=Launch(LaunchKind.PATH, path),
        source="test",
        aliases=generate(name, extra),
    )


