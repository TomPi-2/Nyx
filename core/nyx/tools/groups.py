"""Grupos de herramientas (0.6, tarea 6.20b).

El modelo no ve todas las herramientas en cada petición: ve unas pocas **fijas** (lo más
frecuente) y los **grupos** cuyo tema aparece en la frase, elegidos por código
(`brain/select.py`, en la CPU). Así lo que ocupa el prompt no crece con lo instalado: con 40
herramientas o con 400 (extensiones, 0.7), el modelo ve más o menos lo mismo.

Medido en el PC de referencia (`docs/benchmarks/bateria-0.6.md` y PLAN-0.6 §6.20): con la
lista en caché, el primer token sale en 0,07 s; cambiar de grupo obliga a evaluar solo la parte
que cambia (las fijas van primero), unos 0,3–0,8 s según el tamaño del grupo. Por eso los
grupos son pequeños (tope en `MAX_GROUP_CHARS`, lo exige una prueba) y la lista no cambia si
la frase no da pistas (`select.py`).

Las palabras clave son expresiones regulares sobre el texto normalizado (minúsculas, sin
tildes ni signos: `index.aliases.normalize`). Se buscan al principio de palabra, así que «alarm»
encaja con «alarma» y «alarmas». Ante la duda, mejor que sobre un grupo a que falte: un grupo
de más cuesta unos tokens; uno de menos deja al modelo sin la herramienta.
"""

